// Package domain is the Webhook context: outgoing webhooks of a project (signed HTTP callbacks for
// its domain events) and "development" links from Git hosting (commits and pull requests that
// mention an issue key).
package domain

import (
	"context"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"net"
	"net/url"
	"regexp"
	"slices"
	"strings"
	"time"
)

var (
	ErrInvalidWebhook  = errors.New("invalid webhook")
	ErrWebhookNotFound = errors.New("webhook not found")
)

// AllEvents subscribes a webhook to every event of its project.
const AllEvents = "*"

const (
	maxURL    = 2048
	maxEvents = 50
)

var eventName = regexp.MustCompile(`^[a-z][a-z_]*(\.[a-z][a-z_]*)+$`)

type ID string

// Webhook posts a project's matching events to URL, signed with Secret.
type Webhook struct {
	ID        ID
	Project   string // project key
	URL       string
	Secret    string // HMAC-SHA256 key; shown once when the webhook is created
	Events    []string
	Active    bool
	CreatedBy string
	CreatedAt time.Time
}

// New configures an active webhook; the secret is generated by the caller.
func New(id ID, project, rawURL, secret string, events []string, by string, at time.Time) (*Webhook, error) {
	if secret == "" {
		return nil, fmt.Errorf("%w: secret is required", ErrInvalidWebhook)
	}
	w := &Webhook{ID: id, Project: project, Secret: secret, CreatedBy: by, CreatedAt: at}
	if err := w.Reconfigure(rawURL, events, true); err != nil {
		return nil, err
	}
	return w, nil
}

// Reconfigure changes where and what the webhook delivers, and whether it is active.
func (w *Webhook) Reconfigure(rawURL string, events []string, active bool) error {
	u, err := ValidURL(rawURL)
	if err != nil {
		return err
	}
	ev, err := validEvents(events)
	if err != nil {
		return err
	}
	w.URL, w.Events, w.Active = u, ev, active
	return nil
}

// ValidURL accepts https URLs, and plain http only for the local machine (development).
func ValidURL(raw string) (string, error) {
	raw = strings.TrimSpace(raw)
	u, err := url.Parse(raw)
	if err != nil || len(raw) > maxURL || u.Host == "" || u.User != nil {
		return "", fmt.Errorf("%w: url must be an absolute http(s) URL without credentials", ErrInvalidWebhook)
	}
	switch u.Scheme {
	case "https":
	case "http":
		if !Local(u.Hostname()) {
			return "", fmt.Errorf("%w: plain http is allowed only for localhost", ErrInvalidWebhook)
		}
	default:
		return "", fmt.Errorf("%w: url must use https", ErrInvalidWebhook)
	}
	u.Fragment = ""
	return u.String(), nil
}

// Local reports whether host names the local machine.
func Local(host string) bool {
	if strings.EqualFold(host, "localhost") {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}

func validEvents(events []string) ([]string, error) {
	var out []string
	for _, e := range events {
		e = strings.TrimSpace(e)
		if e != AllEvents && !eventName.MatchString(e) {
			return nil, fmt.Errorf("%w: unknown event name %q", ErrInvalidWebhook, e)
		}
		if !slices.Contains(out, e) {
			out = append(out, e)
		}
	}
	if len(out) == 0 || len(out) > maxEvents {
		return nil, fmt.Errorf("%w: choose 1-%d events (or \"*\")", ErrInvalidWebhook, maxEvents)
	}
	slices.Sort(out)
	return out, nil
}

// Wants reports whether the webhook, when active, delivers the event.
func (w *Webhook) Wants(event string) bool {
	return w.Active && (slices.Contains(w.Events, AllEvents) || slices.Contains(w.Events, event))
}

// Sign is the X-Kyber-Signature value of body: "sha256=" + hex HMAC-SHA256 with secret.
func Sign(secret string, body []byte) string {
	m := hmac.New(sha256.New, []byte(secret))
	m.Write(body)
	return "sha256=" + hex.EncodeToString(m.Sum(nil))
}

// Verify checks a "sha256=<hex>" signature of body (GitHub's X-Hub-Signature-256) in constant time.
func Verify(secret string, body []byte, signature string) bool {
	return secret != "" && hmac.Equal([]byte(Sign(secret, body)), []byte(signature))
}

// Repository stores webhooks in the workspace of ctx.
type Repository interface {
	Save(ctx context.Context, w *Webhook) error
	ByID(ctx context.Context, id ID) (*Webhook, error)
	// ForProject lists a project's webhooks, oldest first.
	ForProject(ctx context.Context, project string) ([]*Webhook, error)
	// Delete removes a webhook and its deliveries.
	Delete(ctx context.Context, id ID) error
}
